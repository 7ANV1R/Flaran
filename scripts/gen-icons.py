#!/usr/bin/env python3
"""Regenerate Sources/Flaran/Icons.generated.swift from the icon package.

    npm pack @hugeicons/core-free-icons && tar -xzf hugeicons-core-free-icons-*.tgz
    python3 scripts/gen-icons.py package/dist/esm
"""
import re
import sys
from pathlib import Path

# Swift case name -> package export name
ICONS = {
    "reload": "FlashIcon",
    "restart": "RefreshIcon",
    "stop": "StopIcon",
    "play": "PlayIcon",
    "devtools": "Wrench01Icon",
    "logs": "CommandLineIcon",
    "chevronRight": "ArrowRight01Icon",
    "chevronLeft": "ArrowLeft01Icon",
    "folder": "Folder01Icon",
    "folderAdd": "FolderAddIcon",
    "phone": "SmartPhone01Icon",
    "tablet": "Tablet01Icon",
    "desktop": "ComputerIcon",
    "globe": "GlobeIcon",
    "apple": "AppleIcon",
    "android": "AndroidIcon",
    "close": "Cancel01Icon",
    "alert": "Alert02Icon",
    "check": "Tick02Icon",
    "power": "PowerIcon",
    "command": "CommandIcon",
    "copy": "Copy01Icon",
    "trash": "Delete02Icon",
    "refresh": "ReloadIcon",
}


def to_svg(js: str) -> str:
    parts = []
    for tag, attrs in re.findall(r'\["(\w+)",\s*\{([^}]*)\}\]', js):
        kv = re.findall(r'(\w+):\s*"([^"]*)"', attrs)
        rendered = " ".join(
            f'{re.sub(r"([A-Z])", lambda m: "-" + m[1].lower(), k)}="{v.replace("currentColor", "black")}"'
            for k, v in kv if k != "key")
        parts.append(f"<{tag} {rendered}/>")
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24" fill="none">'
            + "".join(parts) + "</svg>")


def main(src: Path) -> None:
    lines = [
        "// Generated by scripts/gen-icons.py. Do not edit.",
        "",
        "enum Glyph: String {",
    ]
    for name, export in ICONS.items():
        svg = to_svg((src / f"{export}.js").read_text())
        lines.append(f'    case {name} = ##"{svg}"##')
    lines.append("}")
    out = Path(__file__).resolve().parent.parent / "Sources/Flaran/Icons.generated.swift"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(ICONS)} icons to {out}")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
